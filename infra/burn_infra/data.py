"""BurnData (owner: L0). Shared state every other stack uses by name.

- DynamoDB tables from contracts/README.md (on-demand billing, so idle cost ~0).
- System secrets with values generated by AWS at deploy time, so no value
  ever passes through this repo or a developer's terminal.
"""
import aws_cdk as cdk
from aws_cdk import aws_dynamodb as ddb
from aws_cdk import aws_secretsmanager as sm
from constructs import Construct

S = ddb.AttributeType.STRING


class BurnDataStack(cdk.Stack):
    def __init__(self, scope: Construct, construct_id: str, **kwargs) -> None:
        super().__init__(scope, construct_id, **kwargs)

        def table(name: str, pk: str, sk: str | None = None) -> ddb.Table:
            return ddb.Table(
                self, name,
                table_name=name,
                partition_key=ddb.Attribute(name=pk, type=S),
                sort_key=ddb.Attribute(name=sk, type=S) if sk else None,
                billing_mode=ddb.BillingMode.PAY_PER_REQUEST,
                removal_policy=cdk.RemovalPolicy.DESTROY,  # hackathon: teardown must be clean
            )

        events = table("burn-events", "stream", "event_id")
        events.add_global_secondary_index(
            index_name="by_agent",
            partition_key=ddb.Attribute(name="agent_id", type=S),
            sort_key=ddb.Attribute(name="event_id", type=S),
        )

        table("burn-exposures", "agent_id", "secret_ref_or_fp")

        credentials = table("burn-credentials", "secret_ref")
        credentials.add_global_secondary_index(
            index_name="by_owner", partition_key=ddb.Attribute(name="owner_agent_id", type=S)
        )

        fingerprints = table("burn-fingerprints", "fingerprint")
        fingerprints.add_global_secondary_index(
            index_name="by_secret", partition_key=ddb.Attribute(name="secret_ref", type=S)
        )

        sessions = table("burn-sessions", "session_id")
        sessions.add_global_secondary_index(
            index_name="by_agent", partition_key=ddb.Attribute(name="agent_id", type=S)
        )
        sessions.add_global_secondary_index(
            index_name="by_client", partition_key=ddb.Attribute(name="client_id", type=S)
        )

        table("burn-scenario", "pk")
        table("burn-messages", "to_agent", "msg_id")

        # 64 lowercase hex chars = 32-byte HMAC key. Generated by Secrets Manager.
        sm.Secret(
            self, "FingerprintKey",
            secret_name="burn-system/fingerprint-key",
            description="HMAC key for Burn credential fingerprints",
            generate_secret_string=sm.SecretStringGenerator(
                password_length=64,
                exclude_punctuation=True,
                exclude_uppercase=True,
                include_space=False,
                exclude_characters="ghijklmnopqrstuvwxyz",
            ),
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )
        sm.Secret(
            self, "DemoToken",
            secret_name="burn-system/demo-token",
            description="Shared token the dashboard/runner send as x-burn-demo-token",
            generate_secret_string=sm.SecretStringGenerator(
                password_length=40, exclude_punctuation=True, include_space=False
            ),
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )
