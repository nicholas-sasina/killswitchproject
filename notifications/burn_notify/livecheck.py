"""Live check: the step-by-step verification against AUTHORIZED test destinations.

Every message is labelled "[TEST] SYNTHETIC ..." and built from synthetic fixtures; no real
incident or credential is used. Requires --live and BURN_NOTIFY_LIVE=1 (see cli.py).

Sequence, per enabled destination in the config:
  1. canary alert (HIGH)                   -> sent, provider acknowledgement recorded
  2. containment update (session revoked)  -> sent
  3. rotation + flag results               -> recorded for the summary (LOW, not sent)
  4. containment summary (flush)           -> sent with the recorded rotation/flag counts
  5. the canary alert again (duplicate)    -> must send nothing
  6. --inject-failure: a new alert whose first attempt fails twice (simulated connection
     errors before the real request), then an SQS-style redelivery  -> must be delivered once
Each payload is checked with verify.check_payload. Output never contains secrets.
"""
from __future__ import annotations

import json
import time
from dataclasses import dataclass, field, replace

from . import fixtures, verify
from .config import Config
from .processor import Processor
from .providers import REGISTRY
from .secrets import SecretResolver
from .store import MemoryStore

NOTICE = "SYNTHETIC TEST - generated by the BURN notifications live check; not a real security event"


class _Clock:
    def __init__(self):
        self.offset = 0.0

    def __call__(self):
        return time.time() + self.offset


class _Counting:
    """Wraps a real transport: counts real requests, can fail the first N calls before sending."""

    def __init__(self, inner):
        self.inner, self.calls, self.fail_next = inner, 0, 0

    def post(self, url, body, headers, *, timeout):
        if self.fail_next:
            self.fail_next -= 1
            raise ConnectionError("injected failure (no request sent)")
        self.calls += 1
        return self.inner.post(url, body, headers, timeout=timeout)


class _CountingSES:
    def __init__(self, inner):
        self.inner, self.calls, self.fail_next = inner, 0, 0

    def send_email(self, **kwargs):
        if self.fail_next:
            self.fail_next -= 1
            raise ConnectionError("injected failure (no request sent)")
        self.calls += 1
        return self.inner.send_email(**kwargs)


@dataclass
class Step:
    name: str
    event_id: str
    results: list[dict] = field(default_factory=list)


def _capture_payloads(proc: Processor, event: dict) -> dict[str, list[str]]:
    """Render what each destination receives for event and verify it."""
    inc, _ = proc.incident_for(event)
    problems = {}
    for dest in proc.config.destinations:
        body = proc.providers[dest.provider].build(inc, dest).body
        secret = None
        try:
            secret = proc.secrets.get(dest.secret_ref) if dest.secret_ref else None
        except Exception:
            pass
        problems[dest.id] = verify.check_payload(inc, event, body, secrets=(secret,) if secret else ())
    return problems


def run(cfg: Config, *, inject_failure: bool = False, secrets: SecretResolver | None = None,
        providers=None) -> dict:
    clock = _Clock()
    # Every test destination receives the HIGH test sequence (even one configured critical-only), and
    # nothing lower, so each channel gets alert + update + summary (+ the retry probe) and no LOW noise.
    cfg = replace(cfg, destinations=tuple(replace(d, min_severity="high", digest_low=False, rate_per_minute=600)
                                          for d in cfg.destinations if d.enabled), individual_per_window=100)
    counters = {}
    if providers is None:
        providers = {}
        for name, cls in REGISTRY.items():
            if name == "email":
                import boto3
                counters[name] = _CountingSES(boto3.client("sesv2"))
                providers[name] = cls(ses_client=counters[name])
            else:
                real = cls()
                counters[name] = _Counting(real.transport)
                providers[name] = cls(transport=counters[name])
    else:
        for name, p in providers.items():
            if name == "email":
                counters[name] = p._ses = _CountingSES(p._client())
            else:
                counters[name] = p.transport = _Counting(p.transport)
    proc = Processor(cfg, MemoryStore(), providers=providers, secrets=secrets, clock=clock, notice=NOTICE)
    report = {"destinations": [{"id": d.id, "provider": d.provider} for d in cfg.destinations], "steps": []}

    def step(name, event, **kw):
        payload_checks = _capture_payloads(proc, event)
        before = {k: c.calls for k, c in counters.items()}
        result = proc.process_event(event, **kw)
        sent = {k: c.calls - before[k] for k, c in counters.items()}
        rows = []
        for outcome in result.outcomes:
            dest = cfg.destination(outcome.destination_id)
            row = proc.store.get(event["event_id"], dest.id) or {}
            rows.append({"destination": dest.id, "provider": dest.provider, "status": outcome.status,
                         "failure": outcome.category, "attempts": row.get("attempts"),
                         "provider_ref": row.get("provider_ref"),
                         "payload_check": "pass" if not payload_checks.get(dest.id) else payload_checks[dest.id]})
        report["steps"].append({"step": name, "event_id": event["event_id"], "category": result.category,
                                "severity": result.severity, "requests_sent": sent, "results": rows})
        return result

    canary = fixtures.canary_used()
    step("1 canary alert", canary)
    step("2 containment update (session revoked)", fixtures.canary_revoked(offset_ms=1))
    step("3a rotation result", fixtures.rotated(offset_ms=2))
    step("3b shared credential flagged", fixtures.flagged("seen", offset_ms=3))
    clock.offset += 120
    before = {k: c.calls for k, c in counters.items()}
    flushed = proc.flush_windows()
    report["steps"].append({
        "step": "4 containment summary (flush)", "requests_sent": {k: c.calls - before[k] for k, c in counters.items()},
        "results": [{"destination": d, "status": o.status, "failure": o.category,
                     "payload_check": "pass" if not verify.check_payload(inc, None, proc.providers[
                         cfg.destination(d).provider].build(inc, cfg.destination(d)).body) else "fail",
                     "facts": dict(inc.facts)} for (d, inc), o in zip(proc.flushed, flushed)]})
    dup = step("5 duplicate of the canary alert", canary)
    report["duplicate_sent_nothing"] = all(v == 0 for v in report["steps"][-1]["requests_sent"].values()) and \
        all(o.status.startswith("skipped_") for o in dup.outcomes)
    if inject_failure:
        probe = fixtures.blocked(offset_ms=10)
        for c in counters.values():
            c.fail_next = 2  # first attempt + its quick retry fail before any request is made
        step("6a injected failure (first receive)", probe, receive_count=1)
        for c in counters.values():
            c.fail_next = 0
        step("6b SQS redelivery", probe, receive_count=2)
    report["delivery_history"] = proc.store.list_deliveries()
    return report


def render(report: dict) -> str:
    lines = []
    for s in report["steps"]:
        lines.append(f"\n== {s['step']}  {s.get('event_id', '')}  {s.get('severity') or ''}")
        lines.append(f"   provider requests: {json.dumps(s['requests_sent'])}")
        if not s["results"]:
            lines.append("   recorded for the containment summary; not routed (LOW)")
        for r in s["results"]:
            extra = f" ref={r['provider_ref']}" if r.get("provider_ref") else ""
            extra += f" failure={r['failure']}" if r.get("failure") else ""
            lines.append(f"   {r['destination']:<20} {r['status']:<20} payload={r['payload_check']}{extra}")
            if r.get("facts"):
                lines.append(f"      {r['facts'].get('Owned credentials')} | {r['facts'].get('Shared credentials')}")
    lines.append(f"\nduplicate sent nothing: {report.get('duplicate_sent_nothing')}")
    return "\n".join(lines)
